-- Só estas funções podem resolver uma identidade antes de existir um tenant.
-- A listagem pública é intencional para o seletor desta demonstração sem login.
CREATE FUNCTION public.app_demo_users()
RETURNS TABLE(id integer, name text, role text, company_id integer, company_name text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog AS $$
  SELECT u.id, u.name, u.role::text, c.id, c.name
  FROM public.demo_users u JOIN public.companies c ON c.id = u.company_id
  ORDER BY c.id, u.id
$$;
CREATE FUNCTION public.app_resolve_user(p_id integer)
RETURNS TABLE(id integer, name text, role text, company_id integer, company_name text, brand_color text, time_zone text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = pg_catalog AS $$
  SELECT u.id, u.name, u.role::text, c.id, c.name, c.brand_color, c.time_zone
  FROM public.demo_users u JOIN public.companies c ON c.id = u.company_id
  WHERE u.id = p_id
$$;
REVOKE ALL ON FUNCTION public.app_demo_users() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.app_resolve_user(integer) FROM PUBLIC;
