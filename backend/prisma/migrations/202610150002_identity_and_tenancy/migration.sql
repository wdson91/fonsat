ALTER TABLE companies ADD COLUMN brand_color TEXT NOT NULL DEFAULT '#ec405c';
ALTER TABLE companies ADD COLUMN time_zone TEXT NOT NULL DEFAULT 'Europe/Lisbon';
CREATE TYPE "UserRole" AS ENUM ('worker', 'foreman', 'admin', 'client');
CREATE TABLE demo_users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES companies(id),
  name TEXT NOT NULL,
  role "UserRole" NOT NULL,
  UNIQUE (company_id, id), UNIQUE (company_id, name)
);
CREATE TABLE sites (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES companies(id),
  name TEXT NOT NULL,
  UNIQUE (company_id, id), UNIQUE (company_id, name)
);
CREATE TABLE site_responsibilities (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES companies(id),
  site_id INTEGER NOT NULL,
  user_id INTEGER NOT NULL,
  starts_on DATE NOT NULL,
  ends_on DATE,
  FOREIGN KEY (company_id, site_id) REFERENCES sites(company_id, id),
  FOREIGN KEY (company_id, user_id) REFERENCES demo_users(company_id, id),
  UNIQUE (company_id, site_id, user_id, starts_on),
  CHECK (ends_on IS NULL OR ends_on >= starts_on)
);
CREATE INDEX ON site_responsibilities (company_id, user_id, starts_on);

